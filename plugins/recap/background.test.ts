import { afterEach, expect, it, vi } from "vitest";
import { BackgroundRecaps } from "./background";
afterEach(() => vi.useRealTimers());
it("waits 180s, ignores repeat visits and serializes automatic jobs globally", async () => {
  vi.useFakeTimers();
  const calls: string[] = [];
  let finish!: () => void;
  const scheduler = new BackgroundRecaps(async (id) => { calls.push(id); await new Promise<void>((resolve) => { finish = resolve; }); }, () => {});
  scheduler.observe("a", 1, true);
  await vi.advanceTimersByTimeAsync(100_000);
  scheduler.observe("a", 1, true);
  scheduler.observe("b", 1, true);
  await vi.advanceTimersByTimeAsync(80_000);
  expect(calls).toEqual(["a"]);
  await vi.advanceTimersByTimeAsync(100_000);
  expect(calls).toEqual(["a"]);
  finish(); await vi.advanceTimersByTimeAsync(0);
  expect(calls).toEqual(["a", "b"]);
  finish(); await vi.advanceTimersByTimeAsync(0);
  scheduler.dispose();
});
it("resets execution/history activity, rearms config changes, forgets removed sources and clears timers on disposal", async () => {
  vi.useFakeTimers();
  const run = vi.fn(async () => {});
  const scheduler = new BackgroundRecaps(run, () => {});
  scheduler.observe("a", 1, true);
  await vi.advanceTimersByTimeAsync(100_000);
  scheduler.observe("a", 2, false, true);
  await vi.advanceTimersByTimeAsync(180_000);
  expect(run).not.toHaveBeenCalled();
  scheduler.observe("a", 2, true, true);
  await vi.advanceTimersByTimeAsync(180_000);
  expect(run).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(180_000);
  expect(run).toHaveBeenCalledTimes(1);
  scheduler.invalidate();
  await vi.advanceTimersByTimeAsync(180_000);
  expect(run).toHaveBeenCalledTimes(2);
  scheduler.observe("removed", 1, true);
  scheduler.forget("removed");
  scheduler.observe("disposed", 1, true);
  scheduler.dispose();
  await vi.advanceTimersByTimeAsync(360_000);
  expect(run).toHaveBeenCalledTimes(2);
  expect(vi.getTimerCount()).toBe(0);
});
it("contains callback failures without retrying an unchanged version or losing the next source", async () => {
  vi.useFakeTimers();
  const errors = vi.fn();
  const run = vi.fn(async (id: string) => { if (id === "bad") throw new Error("offline"); });
  const scheduler = new BackgroundRecaps(run, errors);
  scheduler.observe("bad", 1, true);
  scheduler.observe("next", 1, true);
  await vi.advanceTimersByTimeAsync(180_001);
  expect(run.mock.calls.map(([id]) => id)).toEqual(["bad", "next"]);
  expect(errors).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(180_000);
  expect(run).toHaveBeenCalledTimes(2);
  scheduler.dispose();
});
